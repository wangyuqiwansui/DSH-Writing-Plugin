import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const base = process.env.PREVIEW_URL ?? 'http://127.0.0.1:4186'
const output = resolve(process.env.OUTPUT_DIR ?? '.harness-analysis/ANALYSIS_20261023_QUALITY_BODY/browser')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const results = { cases: [], screenshots: [], errors: [], overflow: [] }
page.on('pageerror', error => results.errors.push(error.message))
const screenshot = async name => { const path = resolve(output, `${name}.png`); await page.screenshot({ path }); results.screenshots.push(path) }
const overflow = async () => {
  const values = await page.evaluate(() => ['html', '.ww-content', '.wq-page'].map(selector => { const e = document.querySelector(selector); return { selector, client: e.clientWidth, scroll: e.scrollWidth } }))
  assert.ok(values.every(item => item.scroll <= item.client + 1), JSON.stringify(values)); results.overflow.push({ width: page.viewportSize().width, values })
}
try {
  await page.goto(`${base}/?demo=quality`)
  await page.getByRole('heading', { name: '质量检测', exact: true }).waitFor()
  await page.getByRole('tab', { name: 'L0 Policy · 全局规则', exact: true }).waitFor()
  await page.locator('.wq-rule-row').first().waitFor()
  assert.equal(await page.getByRole('tab').count(), 2)
  assert.equal(await page.getByRole('tab', {name: /历史报告|污染观察|L2/}).count(), 0)
  await overflow(); await screenshot('desktop-l0')
  await page.getByRole('tab', { name: 'L1 Project · 项目规则', exact: true }).click()
  await page.locator('.wq-rule-row').first().waitFor(); await screenshot('desktop-l1')
  await page.getByRole('button', {name: '检测正文', exact: true}).click()
  await page.getByRole('button', { name: '预览检测', exact: true }).first().waitFor()
  assert.equal(await page.getByRole('combobox', { name: '检测内容类型' }).count(), 0)
  assert.equal(await page.locator('.wq-row').count(), 2)
  assert.ok(!(await page.locator('.wq-list').innerText()).includes('渡口旧事'))
  await overflow(); await screenshot('desktop-detect')
  await page.getByRole('button', { name: '预览检测', exact: true }).first().click()
  await page.getByRole('heading', { name: '检测范围确认' }).waitFor()
  await page.getByRole('button', { name: '开始检测', exact: true }).click()
  await page.getByRole('region', { name: '本次检测结果' }).waitFor()
  assert.ok((await page.getByRole('region', { name: '本次检测结果' }).innerText()).includes('发现问题'))
  await page.locator('.wq-quote').first().click()
  assert.equal(await page.locator('.wq-original mark').innerText(), '<think>')
  await overflow(); await screenshot('desktop-report')
  results.cases.push('Real temporary SQLite detection, report persistence and exact evidence jump')
  await page.getByRole('button', { name: '规则管理', exact: true }).click()
  await page.getByRole('button', { name: '新建规则' }).click()
  await page.getByLabel('规则名称', { exact: true }).fill('界面验收规则')
  await page.getByLabel('规则说明', { exact: true }).fill('禁止正文包含示例占位词。')
  await page.getByLabel('精确匹配文本', { exact: true }).fill('示例占位词')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  const row = page.locator('.wq-rule-row').filter({ has: page.getByRole('heading', { name: '界面验收规则', exact: true }) })
  await row.waitFor(); assert.ok((await row.innerText()).includes('草稿'))
  await row.getByRole('button', { name: '启用', exact: true }).click()
  await row.getByText('已启用', { exact: true }).waitFor()
  await row.getByRole('button', { name: '停用', exact: true }).click()
  await row.getByText('已停用', { exact: true }).waitFor()
  results.cases.push('Rule create draft, explicit activation and retirement persisted through real service')
  const search = page.getByRole('textbox', { name: '搜索质量检测' })
  await search.fill('界面验收'); await search.press('Enter'); await row.waitFor()
  assert.equal(await page.locator('.wq-rule-row').count(), 1)
  await search.fill('不存在的检查记录'); await search.press('Enter'); await page.getByRole('heading', { name: '没有匹配的记录' }).waitFor()
  results.cases.push('Chinese literal search and explicit zero-results state')
  await page.getByRole('button', {name: '检测正文', exact: true}).click()
  await page.getByRole('combobox', { name: '当前项目' }).selectOption('empty')
  await page.getByRole('heading', { name: '没有可检测的正文版本' }).waitFor()
  assert.equal(await page.getByRole('region', { name: '本次检测结果' }).count(), 0)
  results.cases.push('Only L0/L1 and body targets are exposed; project switch clears current result')
  await page.goto(`${base}/?demo=quality&state=error`); await page.getByRole('alert').waitFor()
  assert.equal(await page.getByRole('heading', { name: '没有可检测的正文版本' }).count(), 0)
  await page.goto(`${base}/?demo=quality&state=unconfigured`); await page.getByRole('heading', { name: '数据库尚未就绪' }).waitFor()
  await page.getByRole('button', { name: '配置数据库', exact: true }).click(); await page.getByRole('heading', { name: '数据库配置' }).waitFor()
  await page.goto(`${base}/?page=quality`); await page.getByRole('heading', { name: '质量检测服务未连接' }).waitFor()
  results.cases.push('Failure, unconfigured and disconnected states stay truthful')
  await page.setViewportSize({ width: 375, height: 900 })
  await page.goto(`${base}/?demo=quality`); await page.locator('.wq-rule-row').first().waitFor()
  await overflow(); await screenshot('mobile-l0')
  await page.getByRole('button', {name: '检测正文', exact: true}).click()
  await page.getByRole('button', { name: '预览检测', exact: true }).first().waitFor()
  await overflow(); await screenshot('mobile-detect')
  await page.getByRole('button', { name: '规则管理', exact: true }).click(); await page.getByRole('button', { name: '新建规则' }).click()
  await overflow(); await screenshot('mobile-rules')
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', {name: '检测正文', exact: true}).click()
  await page.getByRole('button', {name: '预览检测', exact: true}).first().click()
  await page.getByRole('heading', {name: '检测范围确认'}).waitFor()
  await page.getByRole('button', {name: '开始检测', exact: true}).click()
  await page.getByRole('region', { name: '本次检测结果' }).waitFor(); await overflow(); await screenshot('mobile-report')
  results.cases.push('375px detection, rule form and report are usable without horizontal overflow')
  assert.deepEqual(results.errors, [])
  await writeFile(resolve(output, 'verification.json'), JSON.stringify(results, null, 2) + '\n')
  console.log(JSON.stringify(results, null, 2))
} catch (error) {
  await screenshot('failure'); console.error(await page.locator('body').innerText()); throw error
} finally { await browser.close() }
