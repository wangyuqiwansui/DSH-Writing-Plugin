import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { build } from 'esbuild'
import './create-wiki-preview.mjs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const base = process.env.PREVIEW_URL ?? 'http://127.0.0.1:4185'
const output = resolve('.harness-analysis/ANALYSIS_20261023_WIKI/browser')
await mkdir(output, { recursive: true })
await build({ entryPoints: ['scripts/preview.tsx'], outfile: '.preview/app.js', bundle: true, platform: 'browser', format: 'iife', jsx: 'automatic', loader: { '.css': 'text' }, define: { 'process.env.NODE_ENV': '"development"' } })
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = [], report = { cases: [], screenshots: [], overflow: [], pageErrors: errors }
page.on('pageerror', error => errors.push(error.message))
const check = name => report.cases.push(name)
const screenshot = async name => { const path = resolve(output, `${name}.png`); await page.screenshot({ path, fullPage: false }); report.screenshots.push(path) }
const overflow = async () => {
  const values = await page.evaluate(() => ['html', '.ww-content', '.ww-wiki'].map(selector => {
    const element = document.querySelector(selector); return { selector, width: element.clientWidth, scrollWidth: element.scrollWidth }
  }))
  assert.ok(values.every(value => value.scrollWidth <= value.width + 1), JSON.stringify(values))
  report.overflow.push({ viewport: page.viewportSize(), values })
}
const openPage = async () => {
  await page.getByRole('button', { name: /江流城：水路与商会/ }).click()
  await page.getByRole('heading', { name: '江流城：水路与商会', exact: true }).waitFor()
}
try {
  await page.goto(`${base}/?demo=wiki`)
  await page.getByRole('heading', { name: 'Wiki', exact: true }).waitFor()
  await openPage()
  assert.equal(await page.locator('.ww-wiki-citation blockquote').innerText(), '江流城依水而建，商会控制渡口。')
  assert.ok((await page.locator('.ww-wiki-citation').first().innerText()).includes('历史版本'))
  await overflow(); await screenshot('desktop-page')
  check('Wiki page renders real fixture content and exact historical evidence')
  await page.getByRole('button', { name: '查看来源原文 →' }).last().click()
  await page.getByRole('heading', { name: '江流城研究 · 解析文本', exact: true }).waitFor()
  assert.ok((await page.locator('.ww-wiki-source-text').innerText()).includes('人物的动机'))
  await page.getByRole('button', { name: '返回上一条内容', exact: false }).click()
  await page.getByRole('heading', { name: '江流城：水路与商会', exact: true }).waitFor()
  check('citation opens the older source version and back restores the page')
  const search = page.getByRole('textbox', { name: '搜索 Wiki 和资料' })
  await search.fill('渡口'); await search.press('Enter')
  await page.getByRole('button', { name: /江流城：水路与商会/ }).waitFor()
  await search.fill('不存在的内容'); await search.press('Enter')
  await page.getByRole('heading', { name: '没有匹配内容' }).waitFor()
  check('Chinese keyword search and truthful no-results state')
  await search.fill(''); await search.press('Enter')
  await page.getByRole('button', { name: '资料库', exact: true }).click()
  await page.getByRole('button', { name: /江流城研究 · 解析文本/ }).click()
  assert.ok((await page.locator('.ww-wiki-source-text').innerText()).includes('新解析版本'))
  await page.getByRole('button', { name: '返回列表', exact: false }).click()
  await page.getByLabel('包含已失效资料').check()
  await page.getByRole('button', { name: /旧渡口记录/ }).click()
  await page.getByText('此来源已失效，仅供历史追溯。 资料内容有误', { exact: true }).waitFor()
  await screenshot('desktop-revoked-source')
  check('source list uses latest revisions and withdrawn sources require an explicit filter')
  await page.getByRole('combobox', { name: '当前项目' }).selectOption('q')
  await page.getByRole('heading', { name: '还没有资料', exact: true }).waitFor()
  assert.equal(await page.locator('.ww-wiki-source-text').count(), 0)
  check('project change clears source content and shows project-specific empty state')
  await page.goto(`${base}/?demo=wiki&state=error`)
  await page.getByRole('alert').waitFor()
  await page.getByRole('heading', { name: '列表暂时无法读取' }).waitFor()
  assert.equal(await page.getByRole('heading', { name: '还没有Wiki 页面' }).count(), 0)
  check('read failures remain errors rather than empty collections')
  await page.goto(`${base}/?demo=wiki&state=empty`)
  await page.getByRole('heading', { name: '数据库中还没有项目' }).waitFor()
  await page.goto(`${base}/?demo=wiki&state=unconfigured`)
  await page.getByRole('heading', { name: '请先连接数据库' }).waitFor()
  await page.getByRole('button', { name: '配置数据库', exact: true }).click()
  await page.getByRole('heading', { name: '数据库配置', exact: true }).waitFor()
  await page.goto(`${base}/?page=wiki`)
  await page.getByRole('heading', { name: '等待连接 DSH 宿主' }).waitFor()
  check('empty database, unconfigured and standalone host states are explicit')
  await page.setViewportSize({ width: 375, height: 900 })
  await page.goto(`${base}/?demo=wiki`); await openPage()
  await overflow(); await screenshot('mobile-page')
  assert.equal(await page.locator('.ww-wiki-listpane').isVisible(), false)
  await page.getByRole('button', { name: '查看来源原文 →' }).last().click()
  await page.getByRole('heading', { name: '江流城研究 · 解析文本', exact: true }).waitFor()
  await overflow(); await screenshot('mobile-source')
  await page.getByRole('button', { name: '返回列表', exact: false }).click()
  assert.equal(await page.locator('.ww-wiki-listpane').isVisible(), true)
  await page.getByRole('button', { name: '切换工作台导航' }).click()
  await page.getByRole('button', { name: '▦ 工作台', exact: true }).click()
  await page.getByRole('button', { name: /打开 Wiki/ }).click()
  await page.getByRole('heading', { name: 'Wiki', exact: true }).waitFor()
  check('375px reading, long references, mobile navigation and home entry')
  assert.deepEqual(errors, [])
  await writeFile(resolve(output, 'verification.json'), JSON.stringify(report, null, 2) + '\n')
  console.log(JSON.stringify(report, null, 2))
} finally { await browser.close() }
